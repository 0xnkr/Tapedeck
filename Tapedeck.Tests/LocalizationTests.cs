using System.Runtime.CompilerServices;
using System.Text.RegularExpressions;
using System.Xml.Linq;

namespace Tapedeck.Tests;

/// <summary>Every translation of the UI texts has the same keys and placeholders as the English base file.</summary>
public sealed partial class LocalizationTests
{
    [GeneratedRegex(@"\{\d+(:[^}]*)?\}")]
    private static partial Regex Placeholder();

    public static TheoryData<string> Translations()
    {
        var data = new TheoryData<string>();
        foreach (var file in Directory.EnumerateFiles(ResourcesDir(), "Strings.*.resx"))
            data.Add(Path.GetFileName(file));
        return data;
    }

    [Theory]
    [MemberData(nameof(Translations))]
    public void Translation_matches_english_keys_and_placeholders(string fileName)
    {
        var english = Read("Strings.resx");
        var translation = Read(fileName);

        Assert.Equal(english.Keys.Order(), translation.Keys.Order());
        foreach (var (key, text) in english)
            Assert.True(Placeholders(text).SequenceEqual(Placeholders(translation[key])), $"Placeholders differ for {key}");
    }

    [Fact]
    public void Designer_class_is_in_sync_with_english_keys()
    {
        // Strings.Designer.cs is regenerated by the IDE; editing the resx elsewhere leaves it stale
        var designer = File.ReadAllText(Path.Combine(ResourcesDir(), "Strings.Designer.cs"));
        var properties = Regex.Matches(designer, @"public static string (\w+)").Select(m => m.Groups[1].Value);

        Assert.Equal(Read("Strings.resx").Keys.Order(), properties.Order());
    }

    private static IEnumerable<string> Placeholders(string text) =>
        Placeholder().Matches(text).Select(m => m.Value).Order();

    private static Dictionary<string, string> Read(string fileName) =>
        XDocument.Load(Path.Combine(ResourcesDir(), fileName)).Root!
            .Elements("data")
            .ToDictionary(d => (string)d.Attribute("name")!, d => (string)d.Element("value")!);

    private static string ResourcesDir([CallerFilePath] string testFile = "") =>
        Path.Combine(Path.GetDirectoryName(testFile)!, "..", "Tapedeck", "Resources");
}
